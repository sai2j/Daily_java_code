import java.util.PriorityQueue;

public class PriorityQueueDemo1 {
          public static void main(String[] args) {
                    PriorityQueue<Object> pq = new PriorityQueue<>();
                    pq.add("Orange");
                    pq.add("Apple");
                    pq.add("Mango");
                    pq.add("Gaurav");
                    pq.add("Grapes");

                    System.out.println(pq);
          }
}